'use strict';

/**
 * Build script — sab kuch ek self-contained index.html me daal deta hai
 * (CSS + JS + Devanagari font inline). Isse site file-preview me bhi
 * poore design ke saath dikhti hai, aur server bhi wahi file serve karta hai.
 *
 * Run:  node build.js
 */

const fs = require('fs');
const path = require('path');

const PUB = path.join(__dirname, 'public');
const read = (f) => fs.readFileSync(path.join(PUB, f), 'utf8');
const b64 = (f) => fs.readFileSync(path.join(PUB, f)).toString('base64');

let css = read('styles.css');

// fonts -> data URIs (preview iframes me network nahi hota)
const devFont = b64('fonts/noto-sans-devanagari.woff2');
const latFont = b64('fonts/noto-sans-devanagari-latin.woff2');
css = css
  .replace("url('/fonts/noto-sans-devanagari.woff2')", `url(data:font/woff2;base64,${devFont})`)
  .replace("url('/fonts/noto-sans-devanagari-latin.woff2')", `url(data:font/woff2;base64,${latFont})`);

const extraCss = `
/* preview / offline banner */
.offline-bar {
  position: relative; z-index: 60;
  background: linear-gradient(90deg, #fff3dc, #ffe9c2);
  border-bottom: 1px solid #f0d59b;
  color: #7a4b00; font-size: 12.8px; line-height: 1.45;
  padding: 9px 16px; text-align: center; font-weight: 600;
}
.offline-bar b { color: #5c3800; }
body.has-offline-bar .nav { top: 0; }
`;

const js = [
  '/* ---- symbols ---- */\n' + read('symbols.js'),
  '/* ---- offline/preview mode ---- */\n' + read('offline.js'),
  '/* ---- app ---- */\n' + read('app.js'),
].join('\n\n');

let html = read('template.html');
// NOTE: replacement ko function me dena zaroori hai — warna JS ke `$$`/`$'`
// jaise patterns replace-string me special maane jaate hain aur code corrupt ho jata hai.
html = html.replace('<!-- INLINE_CSS_MARKER -->', () => `<style>\n${css}\n${extraCss}</style>`);
html = html.replace('<!-- INLINE_JS_MARKER -->', () => `<script>\n${js}\n</script>`);

/* FIX: CSS aur JS ab index.html ke andar hi inline hain, isliye purane
   external <link>/<script> tags hata do. Warna single-file deploy
   (GitHub Pages) par /styles.css aur /symbols.js ka 404 aata rehta hai. */
html = html
  .replace(/\s*<link rel="stylesheet" href="\/styles\.css"\s*\/?>/i, '')
  .replace(/\s*<script src="\/symbols\.js"><\/script>/i, '');

// self-contained file sirf ek jagah nahi — do jagah likhi jaati hai:
//   public/index.html  -> server isi ko serve karta hai
//   index.html (root)  -> GitHub Pages (branch root) isi ko serve karta hai
fs.mkdirSync(PUB, { recursive: true });
fs.writeFileSync(path.join(PUB, 'index.html'), html, 'utf8');
fs.writeFileSync(path.join(__dirname, 'index.html'), html, 'utf8');

// Jekyll ko band karo — GitHub Pages bina processing ke file jaisi hai waisi serve kare
const nojekyll = path.join(__dirname, '.nojekyll');
if (!fs.existsSync(nojekyll)) fs.writeFileSync(nojekyll, '', 'utf8');

// config.js user ki apni file hai (GitHub Pages usi ko padhta hai) — use chhua nahi jaata.
// GitHub Action se aane wala server URL alag file `api-base.js` me likha jaata hai
// (JANMAT_API_BASE env variable se), taaki user ki setting kabhi overwrite na ho.
const configSrc = path.join(__dirname, 'config.js');
if (fs.existsSync(configSrc)) fs.copyFileSync(configSrc, path.join(PUB, 'config.js'));

const apiBaseEnv = String(process.env.JANMAT_API_BASE || '').trim().replace(/\/+$/, '');
const apiBaseJs = apiBaseEnv
  ? `/* auto-generated by GitHub Action */\nwindow.JANMAT_API_BASE = '${apiBaseEnv}';\n`
  : `/* koi server URL set nahi (GitHub Action variable: API_BASE) */\nwindow.JANMAT_API_BASE = window.JANMAT_API_BASE || '';\n`;
fs.writeFileSync(path.join(__dirname, 'api-base.js'), apiBaseJs, 'utf8');
fs.writeFileSync(path.join(PUB, 'api-base.js'), apiBaseJs, 'utf8');
if (apiBaseEnv) console.log(`🔗 API base injected: ${apiBaseEnv}`);

const kb = (Buffer.byteLength(html) / 1024).toFixed(1);
console.log(`✅ built index.html + public/index.html (${kb} KB, self-contained)`);
